"""Таблицы и привязки ПЛК-части IIoT-стека из схемы данных (ST в раскладке src/).

Источники — те же файлы, по которым настроены эмулятор, Telegraf и дашборды:

- ``schema/telemetry_catalog.csv`` — метрики: топик ``<device>/<metric>``, вид, единица, зона
  нечувствительности, путь в ПЛК, обратная логика сигнала (``invert``);
- ``schema/command_whitelist.csv`` — белый список команд MQTT и путь команды в ``GVL_Hmi`` или
  ``GVL_Station`` флагмана;
- ``schema/source/scada_alarms.csv``, ``station_alarms.csv`` — тревоги флагмана: номер, код, бит в
  словах тревог, приоритет;
- ``schema/source/scada_tags.csv``, ``station_tags.csv`` — типы данных и пути тегов флагмана (слова
  тревог, режим, NE 107, счётчик команд).

Результат (не редактировать вручную):

- ``src/GVLs/Generated/GVL_IiotMap.gvl.st`` — размеры и таблицы настроек (``VAR_GLOBAL CONSTANT``),
  индексы метрик ``PT_<DEVICE>_<METRIC>``: ядро шлюза, собирается в этом репозитории;
- ``flagship/src/POUs/Iiot/FB_IiotKnsMap/`` — чтение значений и слов тревог из ``GVL_Devices``,
  ``GVL_IO``, ``GVL_Station`` флагмана, запись принятых команд в ``GVL_Hmi`` и ``GVL_Station``,
  состояние обработки команды устройством. Собирается только во флагмане (типы ``PL.*`` и его
  глобальные списки): пути проверяет ``tests_stack/test_flagship_binding.py`` по снимку флагмана.

Запуск: ``python tools_project/gen_plc_iiot.py`` (запись) или ``--check`` (код 1, если файлы устарели).
"""

from __future__ import annotations

import argparse
import csv
import math
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCHEMA = REPO / "schema"
OUT_GVL = REPO / "src" / "GVLs" / "Generated" / "GVL_IiotMap.gvl.st"
OUT_FB = REPO / "flagship" / "src" / "POUs" / "Iiot" / "FB_IiotKnsMap"

HEADER = "// AUTO-GENERATED by gen_plc_iiot.py — не редактировать; источник: {src}"
SOURCES = "schema/ (метрики, команды, тревоги)"
GVL_PREFIX = "Application."
FB_KINDS = {"AnalogInput", "DigitalInput", "Motor", "MotorVfd", "Pid"}  # устройства с stSts.stCommon
VFD_COMM_METRICS = {"speed", "vfd_fault_code"}  # bad при потере связи с ПЧ (data_schema.md, 3.2)
PERIODIC_ONLY = {("PLC1", "uptime")}  # время работы — только с контрольной публикацией
ANALOG_DECIMALS = 3
CONVERT = {
    "BOOL": "BOOL_TO_LREAL({})",
    "INT": "INT_TO_LREAL(TO_INT({}))",  # перечисления на INT (strict): только через TO_INT
    "UINT": "UINT_TO_LREAL({})",
    "UDINT": "UDINT_TO_LREAL({})",
    "WORD": "WORD_TO_LREAL({})",
    "REAL": "REAL_TO_LREAL({})",
}
COMMANDS = (
    "SetAuto",
    "SetManual",
    "SetOos",
    "Start",
    "Stop",
    "SpeedSp",
    "ResetMaint",
    "SubstValue",
    "Ack",
    "Reset",
    "AckReq",
    "ShelveReq",
    "UnshelveReq",
    "SetStepped",
    "SetLevelPid",
    "AckAll",
    "ResetAll",
    "Silence",
)
PRIORITIES = ("Low", "Medium", "High", "Critical")
LIMIT = 120


def read_csv(path: Path) -> list[dict[str, str]]:
    lines = [ln for ln in path.read_text(encoding="utf-8").splitlines() if ln and not ln.startswith("#")]
    return list(csv.DictReader(lines, delimiter=";"))


def strip_app(path: str) -> str:
    return path[len(GVL_PREFIX) :] if path.startswith(GVL_PREFIX) else path


def st_string(text: str) -> str:
    if any(ord(c) > 0x7E or ord(c) < 0x20 or c in "'$" for c in text):
        raise ValueError(f"не ASCII-литерал ST: {text!r}")
    return f"'{text}'"


def st_real(value: float) -> str:
    text = repr(float(value))
    return text if "." in text or "e" in text else text + ".0"


@dataclass(frozen=True)
class Point:
    index: int
    device: str
    metric: str
    unit: str
    kind: str  # Analog | Integer
    deadband: float
    decimals: int
    periodic_only: bool
    value_expr: str | None  # None — заполняет PRG_Iiot (метрики узла)
    valid_expr: str
    ne107_expr: str | None
    comm_expr: str | None  # условие «нет связи с ПЧ»

    @property
    def const(self) -> str:
        return f"PT_{self.device}_{self.metric.upper()}"


@dataclass(frozen=True)
class Rule:
    index: int
    device: str
    command: str
    has_range: bool
    vmin: float
    vmax: float
    target: str
    value_type: str
    dev_index: int


@dataclass(frozen=True)
class Alarm:
    index: int
    alarm_id: int
    device: str
    suffix: str
    slot: int
    priority: str
    words_index: int


def device_types(tags: list[dict[str, str]]) -> dict[str, str]:
    out: dict[str, str] = {}
    for row in tags:
        if row["device"] and row["device_type"]:
            out[row["device"]] = row["device_type"]
    return out


def tag_types(tags: list[dict[str, str]]) -> dict[str, str]:
    return {row["tag"]: row["data_type"] for row in tags}


def tag_paths(tags: list[dict[str, str]]) -> dict[str, str]:
    """Тег → путь в ПЛК без ``Application.`` (``P101.CmdSeq`` → ``GVL_Devices.fbP101.stSts.stCommon.uiCmdSeq``)."""
    return {row["tag"]: strip_app(row["plc_path"]) for row in tags if row["plc_path"]}


def dev_path(paths: dict[str, str], device: str, key: str) -> str:
    """Путь тега устройства ``<device>.<key>``; нет тега — ошибка перечня."""
    tag = f"{device}.{key}"
    if tag not in paths:
        raise ValueError(f"нет тега {tag} в перечне флагмана")
    return paths[tag]


def build_points(
    catalog: list[dict[str, str]], dtypes: dict[str, str], ttypes: dict[str, str], paths: dict[str, str]
) -> list[Point]:
    points: list[Point] = []
    for i, row in enumerate(catalog, start=1):
        device, metric, kind = row["device"], row["metric"], row["kind"]
        deadband = float(row["deadband"]) if row["deadband"] else 0.0
        real_counter = kind == "counter" and deadband > 0
        st_kind = "Analog" if kind == "analog" or real_counter else "Integer"
        path = strip_app(row["plc_path"])
        value_expr: str | None = None
        if path:
            dtype = ttypes.get(row["scada_tag"])
            if dtype not in CONVERT:
                raise ValueError(f"{device}/{metric}: тип тега {row['scada_tag']} {dtype!r} не поддержан")
            if row["invert"] == "1":
                if dtype != "BOOL":
                    raise ValueError(f"{device}/{metric}: invert только у BOOL")
                path = f"NOT {path}"
            value_expr = CONVERT[dtype].format(path)
        dev_type = dtypes.get(device, "")
        if dev_type in FB_KINDS:
            valid_tag = f"{device}.Valid"
            valid = paths.get(valid_tag, "TRUE")
            ne107 = f"TO_INT({dev_path(paths, device, 'Ne107')})"
            # потеря связи с ПЧ: отказ (xCommLossIsFault = TRUE) или предупреждение (FALSE) — plc-process-lib
            comm = (
                f"({dev_path(paths, device, 'Fault')} AND PL.GVL_Const.MOT_FLT_COMM_LOSS) <> 0"
                f" OR ({dev_path(paths, device, 'Warning')} AND PL.GVL_Const.MOT_WRN_COMM_LOSS) <> 0"
                if dev_type == "MotorVfd" and metric in VFD_COMM_METRICS
                else None
            )
        else:
            valid, ne107, comm = "TRUE", None, None  # станция KNS1, сигналы без ФБ (K1), узел PLC1
        decimals = ANALOG_DECIMALS if st_kind == "Analog" else 0
        if st_kind == "Analog" and deadband > 0:
            decimals = max(ANALOG_DECIMALS, -math.floor(math.log10(deadband)) + 1)
        points.append(
            Point(
                i,
                device,
                metric,
                row["unit"],
                st_kind,
                deadband,
                decimals,
                (device, metric) in PERIODIC_ONLY,
                value_expr,
                valid,
                ne107,
                comm,
            )
        )
    return points


def build_rules(whitelist: list[dict[str, str]]) -> tuple[list[Rule], list[str]]:
    devices: list[str] = []
    rules: list[Rule] = []
    for i, row in enumerate(whitelist, start=1):
        if row["command"] not in COMMANDS:
            raise ValueError(f"неизвестная команда {row['command']}")
        if row["device"] not in devices:
            devices.append(row["device"])
        has_range = row["value_type"] == "number"
        rules.append(
            Rule(
                i,
                row["device"],
                row["command"],
                has_range,
                float(row["min"]) if has_range and row["min"] else 0.0,
                float(row["max"]) if has_range and row["max"] else 0.0,
                strip_app(row["plc_path"]),
                row["value_type"],
                devices.index(row["device"]) + 1,
            )
        )
    return rules, devices


def build_alarms(rows: list[dict[str, str]]) -> tuple[list[Alarm], list[str]]:
    devices: list[str] = []
    alarms: list[Alarm] = []
    for i, row in enumerate(rows, start=1):
        if row["priority"] not in PRIORITIES:
            raise ValueError(f"приоритет {row['priority']} тревоги {row['code']}")
        device, suffix = row["code"].split(".", 1)
        if device != row["device"]:
            raise ValueError(f"код {row['code']} не совпадает с устройством {row['device']}")
        if device not in devices:
            devices.append(device)
        alarms.append(
            Alarm(i, int(row["id"]), device, suffix, int(row["bit"]), row["priority"], devices.index(device) + 1)
        )
    return alarms, devices


def wrap(line: str, indent: int) -> list[str]:
    """Перенос строки кода длиннее LIMIT после «, » вне строковых литералов."""
    if len(line) <= LIMIT:
        return [line]
    in_str = False
    best = -1
    for i, ch in enumerate(line):
        if ch == "'":
            in_str = not in_str
        elif ch == "," and not in_str and i + 1 < len(line) and line[i + 1] == " " and i < LIMIT - 1:
            best = i
    if best < 0:
        raise ValueError(f"строку не перенести: {line}")
    return [line[: best + 1], *wrap(" " * indent + line[best + 2 :], indent)]


def gvl_text(
    points: list[Point], rules: list[Rule], cmd_devices: list[str], alarms: list[Alarm], alarm_devices: list[str]
) -> str:
    src = SOURCES
    out = [
        HEADER.format(src=src),
        "// Назначение: размеры и таблицы настроек ПЛК-части IIoT-стека КНС-1: метрики телеметрии (топик",
        "//             <site>/<area>/<unit>/<sPath>), белый список команд, тревоги перечня флагмана.",
        "//             Индексы PT_<DEVICE>_<METRIC> — номера метрик в таблице POINT_CFG.",
        "// Документ:   docs/plc_mqtt.md, раздел «Таблицы из схемы данных»",
        "{attribute 'qualified_only'}",
        "VAR_GLOBAL CONSTANT",
        f"    POINT_COUNT : DINT := {len(points)};",
        f"    RULE_COUNT : DINT := {len(rules)};",
        f"    CMD_DEVICE_COUNT : DINT := {len(cmd_devices)};",
        f"    ALARM_COUNT : DINT := {len(alarms)};",
        f"    ALARM_WORDS_COUNT : DINT := {len(alarm_devices)};",
        "",
        "    // Метрики (schema/telemetry_catalog.csv)",
    ]
    out += [f"    {p.const} : DINT := {p.index};" for p in points]
    out += ["", "    POINT_CFG : ARRAY[1..POINT_COUNT] OF ST_IiotPointCfg := ["]
    for n, p in enumerate(points):
        fields = [f"sPath := {st_string(p.device + '/' + p.metric)}"]
        if p.unit:
            fields.append(f"sUnit := {st_string(p.unit)}")
        fields.append(f"eKind := E_IiotValueKind.{p.kind}")
        if p.deadband:
            fields.append(f"rDeadband := {st_real(p.deadband)}")
        fields.append(f"uiDecimals := {p.decimals}")
        if p.periodic_only:
            fields.append("xPeriodicOnly := TRUE")
        tail = "," if n < len(points) - 1 else "];"
        out += wrap(f"        ({', '.join(fields)}){tail}", 9)
    out += [
        "",
        "    // Белый список команд (schema/command_whitelist.csv)",
        "    RULE_CFG : ARRAY[1..RULE_COUNT] OF ST_IiotCmdRule := [",
    ]
    for n, r in enumerate(rules):
        fields = [f"sDevice := {st_string(r.device)}", f"eCommand := E_IiotCommand.{r.command}"]
        if r.has_range:
            fields += ["xRange := TRUE", f"rMin := {st_real(r.vmin)}", f"rMax := {st_real(r.vmax)}"]
        fields.append(f"diDev := {r.dev_index}")
        tail = "," if n < len(rules) - 1 else "];"
        out += wrap(f"        ({', '.join(fields)}){tail}", 9)
    out += [
        "",
        "    // Тревоги (schema/source/scada_alarms.csv, station_alarms.csv): uiSlot — бит в словах тревог,",
        "    // diWords — строка таблицы слов устройства",
        "    ALARM_CFG : ARRAY[1..ALARM_COUNT] OF ST_IiotAlarmCfg := [",
    ]
    for n, a in enumerate(alarms):
        fields = [
            f"udiId := {a.alarm_id}",
            f"sDevice := {st_string(a.device)}",
            f"sSuffix := {st_string(a.suffix)}",
            f"uiSlot := {a.slot}",
            f"ePriority := E_IiotAlarmPriority.{a.priority}",
            f"diWords := {a.words_index}",
        ]
        tail = "," if n < len(alarms) - 1 else "];"
        out += wrap(f"        ({', '.join(fields)}){tail}", 9)
    out.append("END_VAR")
    return "\n".join(out) + "\n"


def method(name: str, comment: str, decl: list[str], body: list[str]) -> dict[str, str]:
    return {
        f"{name}.method.decl.st": "\n".join([f"// {comment}", *decl]) + "\n",
        f"{name}.method.impl.st": "\n".join(body) + "\n",
    }


def guard(table: str, count: str) -> list[str]:
    """Начало Fill*: массив ARRAY[*] меньше перечня — ничего не пишем (индексы в методе — константы)."""
    return [
        "// Массив меньше перечня (не тот, что объявлен в PRG_Iiot): ничего не пишем, а не выходим за границы",
        f"IF LOWER_BOUND({table}, 1) > 1 OR UPPER_BOUND({table}, 1) < {count} THEN",
        "    RETURN;",
        "END_IF",
    ]


def fb_files(
    points: list[Point],
    rules: list[Rule],
    cmd_devices: list[str],
    alarm_devices: list[str],
    paths: dict[str, str],
    dtypes: dict[str, str],
) -> dict[str, str]:
    src = SOURCES
    files: dict[str, str] = {
        "FB_IiotKnsMap.decl.st": "\n".join(
            [
                HEADER.format(src=src),
                "// Назначение: привязка ПЛК-части IIoT-стека к переменным флагмана КНС-1: значения и качество",
                "//             метрик из GVL_Devices.fb<TAG>, GVL_IO и GVL_Station (станция KNS1, регулятор LIC101),",
                "//             слова тревог устройств и станции, запись принятых команд в GVL_Hmi.st<TAG>Cmd,",
                "//             GVL_Station.stStationCmd и stLIC101Cmd, номер и результат последней команды (uiCmdSeq,",
                "//             eCmdResult). Пути — колонка plc_path каталога, белого списка и тегов флагмана.",
                "//             Собирается во флагмане (типы PL.* plc-process-lib, глобальные списки флагмана).",
                "// Автор:      kr0nsch",
                "// Версия:     0.2.0",
                "// Документ:   docs/plc_mqtt.md, раздел «Привязка к флагману»",
                "FUNCTION_BLOCK FB_IiotKnsMap",
            ]
        )
        + "\n",
        "FB_IiotKnsMap.impl.st": "// Тело не используется: работа идёт через методы.\n",
    }
    body: list[str] = guard("aPointTable", "GVL_IiotMap.POINT_COUNT")
    for p in points:
        if p.value_expr is None:
            continue
        t = f"aPointTable[{p.index}]"
        body += wrap(f"{t}.lrValue := {p.value_expr};", 4)
        if p.ne107_expr is None:
            body.append(f"{t}.eQuality := E_IiotQuality.Good;")
        else:
            body += wrap(f"{t}.eQuality := F_IiotQuality(xValid := {p.valid_expr}, iNe107 := {p.ne107_expr});", 4)
        if p.comm_expr is not None:
            first, *rest = p.comm_expr.split(" OR ")
            if rest:
                body.append(f"IF {first}")
                body += [f"   OR {part}" for part in rest[:-1]]
                body.append(f"   OR {rest[-1]} THEN")
            else:
                body += wrap(f"IF {first} THEN", 4)
            body.append(f"    {t}.eQuality := E_IiotQuality.Bad;")
            body.append("END_IF")
    files.update(
        method(
            "FillPoints",
            "Значения и качество метрик с путём в ПЛК (метрики узла PLC1 заполняет PRG_Iiot).",
            ["METHOD FillPoints", "VAR_IN_OUT", "    aPointTable : ARRAY[*] OF ST_IiotPoint;", "END_VAR"],
            body,
        )
    )
    body = guard("aWordTable", "GVL_IiotMap.ALARM_WORDS_COUNT")
    for k, dev in enumerate(alarm_devices, start=1):
        t = f"aWordTable[{k}]"
        body += [
            f"{t}.wActive := {dev_path(paths, dev, 'AlmActive')};",
            f"{t}.wUnack := {dev_path(paths, dev, 'AlmUnack')};",
            f"{t}.wShelved := {dev_path(paths, dev, 'AlmShelved')};",
        ]
        if dtypes.get(dev) in FB_KINDS:
            body += [
                f"{t}.wSuppressed := {dev_path(paths, dev, 'AlmSuppressed')};",
                f"{t}.xOutOfService := {dev_path(paths, dev, 'Mode')} = PL.E_DeviceMode.OutOfService;",
            ]
        else:
            # станция: wAlmShelved — отложенные, подавленные и выведенные вместе (DESIGN 3.1 флагмана)
            body += [f"{t}.wSuppressed := 0;", f"{t}.xOutOfService := FALSE;"]
    files.update(
        method(
            "FillAlarmWords",
            "Слова тревог устройств и станции (строки — источники перечня тревог по порядку ALARM_CFG.diWords).",
            ["METHOD FillAlarmWords", "VAR_IN_OUT", "    aWordTable : ARRAY[*] OF ST_IiotAlarmWords;", "END_VAR"],
            body,
        )
    )
    body = ["ApplyCommand := TRUE;", "CASE diRule OF"]
    for r in rules:
        value = "TRUE" if r.value_type == "pulse" else "rValue"
        body.append(f"    {r.index}:  // {r.device} {r.command}")
        body.append(f"        {r.target} := {value};")
    body += ["ELSE", "    ApplyCommand := FALSE;", "END_CASE"]
    files.update(
        method(
            "ApplyCommand",
            "Записать принятую команду строки diRule белого списка в GVL_Hmi или GVL_Station (импульс или rValue).",
            ["METHOD ApplyCommand : BOOL", "VAR_INPUT", "    diRule : DINT;", "    rValue : REAL;", "END_VAR"],
            body,
        )
    )
    body = ["uiSeq := 0;", "iResult := 0;", "CASE diDev OF"]
    for k, dev in enumerate(cmd_devices, start=1):
        body += [
            f"    {k}:  // {dev}",
            f"        uiSeq := {dev_path(paths, dev, 'CmdSeq')};",
            f"        iResult := TO_INT({dev_path(paths, dev, 'CmdResult')});",
        ]
    body.append("END_CASE")
    files.update(
        method(
            "DeviceCmdState",
            "Счётчик обработанных команд и результат последней команды устройства diDev (ST_IiotCmdRule.diDev).",
            [
                "METHOD DeviceCmdState",
                "VAR_INPUT",
                "    diDev : DINT;",
                "END_VAR",
                "VAR_OUTPUT",
                "    uiSeq : UINT;",
                "    iResult : INT;",
                "END_VAR",
            ],
            body,
        )
    )
    return files


def generate() -> dict[Path, str]:
    tags = read_csv(SCHEMA / "source" / "scada_tags.csv") + read_csv(SCHEMA / "source" / "station_tags.csv")
    dtypes, paths = device_types(tags), tag_paths(tags)
    points = build_points(read_csv(SCHEMA / "telemetry_catalog.csv"), dtypes, tag_types(tags), paths)
    rules, cmd_devices = build_rules(read_csv(SCHEMA / "command_whitelist.csv"))
    alarm_rows = read_csv(SCHEMA / "source" / "scada_alarms.csv") + read_csv(SCHEMA / "source" / "station_alarms.csv")
    alarms, alarm_devices = build_alarms(alarm_rows)
    out = {OUT_GVL: gvl_text(points, rules, cmd_devices, alarms, alarm_devices)}
    for name, text in fb_files(points, rules, cmd_devices, alarm_devices, paths, dtypes).items():
        out[OUT_FB / name] = text
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="только проверить, что файлы актуальны")
    args = parser.parse_args(argv)
    files = generate()
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"устарел: {p.relative_to(REPO).as_posix()}")
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p], encoding="utf-8", newline="\n")
        print(f"записан: {p.relative_to(REPO).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
