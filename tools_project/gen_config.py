def barchart(
    title: str, query: str, x_field: str, *, unit: str, decimals: int, colors: Mapping[str, str], description: str = ""
) -> dict[str, Any]:
    """Вертикальные столбцы по категориям x_field (сутки), рядом — по ряду на устройство цветом colors.

    Подписи значений не выводятся: Grafana уменьшает их до места между концом столбца и краем графика
    (у самого высокого столбца его почти нет), а за неделю столбцы узкие и подписи соседей наложились бы.
    Значение — по шкале и во всплывающей подсказке.
    """
    # Категория — текст (единица string): иначе подпись, похожая на число, получила бы единицу панели
    overrides: list[dict[str, Any]] = [
        {"matcher": {"id": "byName", "options": x_field}, "properties": [{"id": "unit", "value": "string"}]},
        *series_colors(colors),
    ]
    options: dict[str, Any] = {
        "xField": x_field,
        "orientation": "vertical",
        "showValue": "never",
        "barWidth": 0.8,
        "groupWidth": 0.7,
        "stacking": "none",
        "xTickLabelRotation": 0,
        "xTickLabelSpacing": 0,
        "legend": {"showLegend": True, "displayMode": "list", "placement": "bottom", "calcs": []},
        "tooltip": {"mode": "multi", "sort": "none"},
    }
    defaults: dict[str, Any] = {
        "unit": unit,
        "decimals": decimals,
        "color": {"mode": "fixed", "fixedColor": C_NORMAL},
        "custom": {"fillOpacity": 85, "lineWidth": 0, "gradientMode": "none", "axisSoftMin": 0},
        "thresholds": steps(C_NORMAL),
    }
    return {
        "type": "barchart",
        "title": title,
        "description": description,
        "datasource": DS,
        "targets": [target(query)],
        "fieldConfig": {"defaults": defaults, "overrides": overrides},
        "options": options,
    }


# Шрифт подписи над полосой, px (шкалы по приоритетам)
GAUGE_TITLE_SIZE = 14


def bargauge(
    title: str,
    query: str,
    *,
    unit: str,
    decimals: int,
    max_value: float | None = None,
    colors: Mapping[str, str] | None = None,
    names: Mapping[str, tuple[str, str]] | None = None,
    transformations: list[dict[str, Any]] | None = None,
    description: str = "",
) -> dict[str, Any]:
    """Шкалы: полоса — цветом ряда, значение — цветом текста в своём столбце справа.

    colors — ряды по устройству (метка device), цвет по устройству; names — ряды по имени поля:
    поле → (подпись, цвет), например приоритет тревоги после преобразования rowsToFields. Без max_value
    шкала общая для всех рядов: самая длинная полоса — наибольшее значение.

    Подпись по устройству — слева, размер подбирает Grafana (полос всегда три). Подписи по именам полей —
    над полосой и фиксированного размера: число полос зависит от фильтра, а подпись слева Grafana
    подбирает по высоте полосы и обрезает по 40 % ширины — при двух полосах было «Сред…».
    """
    defaults: dict[str, Any] = {
        "unit": unit,
        "decimals": decimals,
        "min": 0,
        "color": {"mode": "fixed", "fixedColor": C_NORMAL},
        "thresholds": steps(C_NORMAL),
    }
    if not names:
        defaults["displayName"] = "${__field.labels.device}"
    if max_value is not None:
        defaults["max"] = max_value
    overrides = series_colors(colors or {}) + [
        {
            "matcher": {"id": "byName", "options": field},
            "properties": [
                {"id": "displayName", "value": text},
                {"id": "color", "value": {"mode": "fixed", "fixedColor": color}},
            ],
        }
        for field, (text, color) in (names or {}).items()
    ]
    panel: dict[str, Any] = {
        "type": "bargauge",
        "title": title,
        "description": description,
        "datasource": DS,
        "targets": [target(query)],
        "fieldConfig": {"defaults": defaults, "overrides": overrides},
        "options": {
            "orientation": "horizontal",
            "displayMode": "basic",
            "valueMode": "text",
            "namePlacement": "top" if names else "left",
            "showUnfilled": True,
            "sizing": "auto",
            "minVizHeight": 16,
            "minVizWidth": 8,
            "maxVizHeight": 300,
            "reduceOptions": {"values": False, "calcs": ["lastNotNull"], "fields": ""},
        },
    }
    if names:
        panel["options"]["text"] = {"titleSize": GAUGE_TITLE_SIZE}
    if transformations:
        panel["transformations"] = transformations
    return panel


# Время в таблицах — до секунды, в поясе дашборда: без миллисекунд столбец уже и ничего не обрезается
TIME_UNIT = "time:YYYY-MM-DD HH:mm:ss"


def column(
    name: str,
    title: str,
    mappings: list[dict[str, Any]] | None = None,
    width: int | None = None,
    *,
    wrap: bool = False,
    align: str | None = None,
) -> dict[str, Any]:
    """Столбец таблицы; wrap — перенос длинного текста по словам вместо обрезки.

    Перенос — только у одного столбца таблицы: высоту строки Grafana считает по самому длинному тексту
    строки, и второй столбец с переносом вылезал бы за строку.
    """
    props: list[dict[str, Any]] = [{"id": "displayName", "value": title}]
    if name == "_time":
        props.append({"id": "unit", "value": TIME_UNIT})
    if mappings:
        props.append({"id": "mappings", "value": mappings})
        props.append({"id": "custom.cellOptions", "value": {"type": "color-text"}})
    if width:
        props.append({"id": "custom.width", "value": width})
    if wrap:
        props.append({"id": "custom.wrapText", "value": True})
    if align:
        props.append({"id": "custom.align", "value": align})
    return {"matcher": {"id": "byName", "options": name}, "properties": props}


