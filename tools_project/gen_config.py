def series_colors(colors: Mapping[str, str]) -> list[dict[str, Any]]:
    """Переопределения цвета рядов по имени устройства: ряд «P101» (или с меткой device=P101) — цветом P101.

    Сопоставление по регулярному выражению, а не по точному имени: до применения displayName Grafana
    называет ряд по полю и меткам (``_value P101``), после pivot — по столбцу (``P101``).
    """
    return [
        {
            "matcher": {"id": "byRegexp", "options": f"^(.*[^A-Za-z0-9])?{name}([^A-Za-z0-9].*)?$"},
            "properties": [{"id": "color", "value": {"mode": "fixed", "fixedColor": color}}],
        }
        for name, color in colors.items()
    ]


def stat(
    title: str,
    query: str,
    *,
    unit: str = "none",
    decimals: int | None = None,
    thresholds: dict[str, Any] | None = None,
    mappings: list[dict[str, Any]] | None = None,
    display_name: str | None = None,
    text_mode: str = "value",
    no_value: str = "нет данных",
    description: str = "",
) -> dict[str, Any]:
    defaults: dict[str, Any] = {
        "unit": unit,
        "color": {"mode": "thresholds"},
        "thresholds": thresholds or steps(C_NORMAL),
        "mappings": mappings or [],
        "noValue": no_value,
    }
    if decimals is not None:
        defaults["decimals"] = decimals
    if display_name:
        defaults["displayName"] = display_name
    return {
        "type": "stat",
        "title": title,
        "description": description,
        "datasource": DS,
        "targets": [target(query)],
        "fieldConfig": {"defaults": defaults, "overrides": []},
        "options": {
            "reduceOptions": {"values": False, "calcs": ["lastNotNull"], "fields": ""},
            "orientation": "auto",
            "textMode": text_mode,
            "colorMode": "value",
            "graphMode": "none",
            "justifyMode": "auto",
            "wideLayout": True,
            "showPercentChange": False,
        },
    }


