def _num(value: float | None) -> str:
    if value is None:
        return ""
    return f"{value:g}"


def render_catalog_table(root: Path) -> str:
    rows = [
        "| Устройство | Метрика | Вид | Ед. | Зона нечувств. | Диапазон | Тег SCADA | Описание |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for m in sc.load_catalog(root):
        rng = f"{_num(m.eng_min)}…{_num(m.eng_max)}" if m.eng_min is not None else ""
        tag = f"`{m.scada_tag}`" if m.scada_tag else "—"
        rows.append(
            f"| `{m.device}` | `{m.metric}` | {m.kind} | {m.unit} | {_num(m.deadband)} | {rng} | {tag}"
            f" | {m.description} |"
        )
    return "\n".join(rows)


def render_whitelist_table(root: Path) -> str:
    by_device: dict[str, list[str]] = {}
    for e in sc.load_whitelist(root):
        label = f"`{e.command}`"
        if e.value_type == "number":
            label += f" ({_num(e.min)}…{_num(e.max)} {e.unit})".replace(" )", ")")
        by_device.setdefault(e.device, []).append(label)
    groups: dict[tuple[str, ...], list[str]] = {}
    for device, cmds in by_device.items():
        groups.setdefault(tuple(cmds), []).append(device)
    rows = ["| Устройства | Разрешённые команды |", "|---|---|"]
    for commands, devices in groups.items():
        rows.append(f"| {', '.join(f'`{d}`' for d in devices)} | {', '.join(commands)} |")
    return "\n".join(rows)


def replace_block(text: str, name: str, body: str) -> str:
    pattern = re.compile(
        rf"(<!-- BEGIN GENERATED: {re.escape(name)} -->\n).*?(<!-- END GENERATED: {re.escape(name)} -->)", re.S
    )
    if not pattern.search(text):
        raise ValueError(f"в docs/data_schema.md нет меток блока {name}")
    return pattern.sub(lambda m: m.group(1) + body + "\n" + m.group(2), text)


def render_data_schema(root: Path) -> str:
    text = (root / "docs" / "data_schema.md").read_text(encoding="utf-8")
    text = replace_block(text, "telemetry-catalog", render_catalog_table(root))
    return replace_block(text, "command-whitelist", render_whitelist_table(root))


