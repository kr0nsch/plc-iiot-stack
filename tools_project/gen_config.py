class Layout:
    """Раскладка панелей по сетке 24 колонки; id панелей по порядку."""

    def __init__(self) -> None:
        self.panels: list[dict[str, Any]] = []
        self.y = 0  # верх текущей строки
        self.x = 0  # следующая свободная колонка
        self.bottom = 0  # низ самой высокой панели текущей строки
        self.next_id = 1

    def row(self, title: str) -> None:
        self.newline()
        self.panels.append(
            {
                "type": "row",
                "id": self.next_id,
                "title": title,
                "collapsed": False,
                "gridPos": {"h": 1, "w": 24, "x": 0, "y": self.y},
                "panels": [],
            }
        )
        self.next_id += 1
        self.y += 1
        self.bottom = self.y

    def newline(self) -> None:
        if self.bottom > self.y:
            self.y = self.bottom
        self.x = 0

    def place(self, panel: dict[str, Any], x: int, y: int, w: int, h: int) -> None:
        """Панель в явной позиции (курсор строки не двигается)."""
        panel["id"] = self.next_id
        panel["gridPos"] = {"h": h, "w": w, "x": x, "y": y}
        self.next_id += 1
        self.panels.append(panel)
        self.bottom = max(self.bottom, y + h)

    def add(self, panel: dict[str, Any], w: int, h: int) -> None:
        if self.x + w > 24:
            self.newline()
        self.place(panel, self.x, self.y, w, h)
        self.x += w

    def stack(self, items: Sequence[tuple[dict[str, Any], int]], w: int) -> None:
        """Колонка шириной w из панелей друг под другом: (панель, высота)."""
        if self.x + w > 24:
            self.newline()
        y = self.y
        for panel, h in items:
            self.place(panel, self.x, y, w, h)
            y += h
        self.x += w


def steps(base: str, *pairs: tuple[float, str]) -> dict[str, Any]:
    return {
        "mode": "absolute",
        "steps": [{"color": base, "value": None}, *({"color": c, "value": v} for v, c in pairs)],
    }


def limit_steps(device: str, normal: str, root: Path) -> dict[str, Any]:
    """Пороги по уставкам тревог устройства (перечень iolistgen): зоны HH/H/L/LL цветом приоритета."""
    lim = sc.alarm_limits(device, root)

    def color(suffix: str) -> str:
        return C_PRIO[lim[suffix][1]]

    base = color("LL") if "LL" in lim else color("L") if "L" in lim else normal
    pairs: list[tuple[float, str]] = []
    if "LL" in lim and "L" in lim:
        pairs.append((lim["LL"][0], color("L")))
    if "L" in lim:
        pairs.append((lim["L"][0], normal))
    elif "LL" in lim:
        pairs.append((lim["LL"][0], normal))
    if "H" in lim:
        pairs.append((lim["H"][0], color("H")))
    if "HH" in lim:
        pairs.append((lim["HH"][0], color("HH")))
    return steps(base, *pairs)


