def outputs(root: Path) -> dict[Path, str]:
    out: dict[Path, str] = {
        root / "telegraf" / "telegraf.d" / "opcua.conf": render_opcua_conf(root),
        root / "telegraf" / "lookup" / "alarm_texts.json": render_alarm_texts(root),
        root / "docs" / "data_schema.md": render_data_schema(root),
    }
    for name, build in DASHBOARDS.items():
        out[root / "grafana" / "dashboards" / name] = render_dashboard(build, root)
    return out


def stale_files(root: Path) -> list[Path]:
    """Сгенерированные файлы, содержимое которых не совпадает с генератором."""
    stale = []
    for path, text in outputs(root).items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(path)
    return stale


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    ap.add_argument("--check", action="store_true", help="только проверить, что файлы актуальны")
    ap.add_argument("--root", type=Path, default=sc.REPO, help="корень репозитория")
    args = ap.parse_args(argv)
    root: Path = args.root.resolve()
    if args.check:
        stale = stale_files(root)
        for path in stale:
            print(f"устарел: {path.relative_to(root).as_posix()}", file=sys.stderr)
        if stale:
            print("запустите: python tools_project/gen_config.py", file=sys.stderr)
            return 1
        print("сгенерированные файлы актуальны")
        return 0
    for path, text in outputs(root).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"записан: {path.relative_to(root).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
