def flux_priority_rank() -> str:
    """Выражение Flux: ранг приоритета r.priority по серьёзности (1 — Critical) для сортировки."""
    expr = str(len(PRIORITY_RU))
    for rank, code in reversed(list(enumerate(PRIORITY_RU, start=1))[:-1]):
        expr = f'if r.priority == "{code}" then {rank} else {expr}'
    return expr


