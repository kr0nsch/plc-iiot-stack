def _devices(devices: Sequence[str]) -> str:
    return " or ".join(f'r.device == "{d}"' for d in devices)


def flux_telemetry(devices: Sequence[str] | None, metric: str, tail: str = "", lookback: str | None = None) -> str:
    """Запрос метрики каталога; lookback — фиксированное окно вместо диапазона дашборда."""
    rng = f"range(start: {lookback})" if lookback else "range(start: v.timeRangeStart, stop: v.timeRangeStop)"
    cond = f'r.metric == "{metric}"' + (f" and ({_devices(devices)})" if devices else "")
    return (
        "from(bucket: v.defaultBucket)\n"
        f"  |> {rng}\n"
        '  |> filter(fn: (r) => r._measurement == "telemetry" and r._field == "value" and r.source == "${source}")\n'
        f"  |> filter(fn: (r) => {cond})\n"
        f"{tail}"
    )


