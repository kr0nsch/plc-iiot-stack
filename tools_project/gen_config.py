def flux_alarm_count(states: Sequence[str], prio: bool = False) -> str:
    cond = " or ".join(f'r._value == "{s}"' for s in states)
    return (
        ALARM_LAST_STATE.format(prio=PRIO_FILTER if prio else "")
        + f'  |> filter(fn: (r) => {cond}, onEmpty: "keep")\n'
        + "  |> count()\n"
    )


def flux_alarm_current_table(prio: bool) -> str:
    return (
        ALARM_LAST_STATE.format(prio=PRIO_FILTER if prio else "")
        + '  |> filter(fn: (r) => r._value != "Normal")\n'
        + '  |> rename(columns: {_value: "state"})\n'
        + '  |> keep(columns: ["_time", "code", "text", "priority", "state"])\n'
        + '  |> sort(columns: ["_time"], desc: true)\n'
    )


def flux_alarm_by_priority() -> str:
    """Срабатывания по приоритетам: строка на каждый приоритет фильтра, и с нулём, по серьёзности.

    Нули из array.from: без них приоритет без срабатываний пропадал бы из панели, и состав полос
    менялся бы от периода к периоду.
    """
    zeros = ", ".join(f'{{priority: "{code}", _value: 0}}' for code in PRIORITY_RU)
    counts = flux_alarm_reason(
        '  |> group(columns: ["priority"])\n  |> count()\n  |> group()\n  |> keep(columns: ["priority", "_value"])\n'
    )
    return (
        'import "array"\n\n'
        f"zeros = array.from(rows: [{zeros}])\n"
        f"  |> filter(fn: (r) => r.priority =~ /^${{priority:regex}}$/)\n\n"
        f"counts = {counts}\n"
        "union(tables: [counts, zeros])\n"
        '  |> group(columns: ["priority"])\n'
        "  |> sum()\n"
        "  |> group()\n"
        # Порядок — по серьёзности, а не по алфавиту кодов (Critical, High, Low, Medium)
        f"  |> map(fn: (r) => ({{r with rank: {flux_priority_rank()}}}))\n"
        '  |> sort(columns: ["rank"])\n'
        '  |> keep(columns: ["priority", "_value"])\n'
    )


def flux_alarm_reason(tail: str) -> str:
    return (
        "from(bucket: v.defaultBucket)\n"
        "  |> range(start: v.timeRangeStart, stop: v.timeRangeStop)\n"
        '  |> filter(fn: (r) => r._measurement == "alarm" and r._field == "reason"'
        f"{PRIO_FILTER})\n"
        '  |> filter(fn: (r) => r._value == "Activated", onEmpty: "keep")\n'
        f"{tail}"
    )


