def table(title: str, query: str, columns: Sequence[dict[str, Any]], description: str = "") -> dict[str, Any]:
    """Таблица; порядок столбцов — порядок columns (преобразование organize), а не порядок из Flux."""
    order = {c["matcher"]["options"]: i for i, c in enumerate(columns)}
    return {
        "type": "table",
        "title": title,
        "description": description,
        "datasource": DS,
        "targets": [target(query)],
        "transformations": [
            {"id": "organize", "options": {"indexByName": order, "excludeByName": {}, "renameByName": {}}}
        ],
        "fieldConfig": {
            "defaults": {
                "color": {"mode": "fixed", "fixedColor": C_NORMAL},
                "custom": {"align": "auto", "cellOptions": {"type": "auto"}, "inspect": False},
                "thresholds": steps(C_NORMAL),
                "mappings": [],
                "noValue": "—",
            },
            "overrides": list(columns),
        },
        "options": {"showHeader": True, "cellHeight": "sm", "footer": {"show": False, "reducer": ["sum"]}},
    }


